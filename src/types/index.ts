export function getSentimentLabel(score: number): {
  emoji: string;
  label: string;
  color: string;
} {
  if (score < 0.1) return { emoji: "😊", label: "Friendly & Positive", color: "#16a34a" };
  if (score < 0.25) return { emoji: "😐", label: "Neutral", color: "#2563eb" };
  if (score < 0.5)  return { emoji: "🤔", label: "Mildly Negative", color: "#d97706" };
  if (score < 0.75) return { emoji: "😠", label: "Hostile", color: "#dc2626" };
  return { emoji: "🚨", label: "Severe Cyberbullying", color: "#7f1d1d" };
}

export function generateReport(result: AnalysisResult): string {
  const { isBullying, cyberbullyingScore, overallScore, detectedLanguages, flaggedWords, contextAnalysis, text, attributeScores } = result;
  const bar = "═".repeat(50);
  const thin = "─".repeat(50);

  const attrLines = PERSPECTIVE_ATTRIBUTES.map((attr) => {
    const score = attributeScores[attr]?.summaryScore?.value ?? 0;
    const pct = Math.round(score * 100);
    const label = score < 0.3 ? "Safe" : score < 0.6 ? "Moderate" : "High Risk";
    return `  ${ATTRIBUTE_ICONS[attr as PerspectiveAttribute]}  ${ATTRIBUTE_LABELS[attr as PerspectiveAttribute].padEnd(20)} ${String(pct + "%").padStart(4)}  [${label}]`;
  });

  const lines = [
    bar,
    "    CYBERBULLYING ANALYSIS REPORT — CyberGuard",
    bar,
    "",
    `Verdict        : ${isBullying ? "⚠️  CYBERBULLYING DETECTED" : "✅  CONTENT APPEARS SAFE"}`,
    `Bullying Score : ${Math.round(cyberbullyingScore * 100)}%`,
    `Toxicity Score : ${Math.round(overallScore * 100)}%`,
    `Languages      : ${detectedLanguages.join(", ") || "English"}`,
    `Flagged Terms  : ${flaggedWords.length > 0 ? flaggedWords.join(", ") : "None"}`,
    "",
    thin,
    "  Attribute Scores",
    thin,
    ...attrLines,
    "",
    thin,
    "  AI Context Analysis",
    thin,
    `  ${contextAnalysis}`,
    "",
    thin,
    "  Analyzed Text",
    thin,
    text.length > 400 ? text.slice(0, 400) + "…" : text,
    "",
    `Generated by CyberGuard  •  ${new Date().toLocaleString()}`,
    bar,
  ];
  return lines.join("\n");
}
